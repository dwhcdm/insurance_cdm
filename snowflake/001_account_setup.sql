-- Helper procedure to apply grants across all environments
CREATE OR REPLACE PROCEDURE SANCTIONS_DEV.PUBLIC.APPLY_GRANTS(db_name VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
    -- SANCTIONS_PLATFORM_ADMIN: Full control
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_PLATFORM_ADMIN';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_PLATFORM_ADMIN';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_PLATFORM_ADMIN';

    -- SANCTIONS_DATA_ENGINEER: Read/write on RAW, STAGING; read on others
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.RAW TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.STAGING TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.CURATED TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.CURATED TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.CURATED TO ROLE SANCTIONS_DATA_ENGINEER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DATA_ENGINEER';

    -- SANCTIONS_ANALYST: Read on ANALYTICS and DERIVED
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.DERIVED TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.CONSUMPTION TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL VIEWS IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE VIEWS IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.DERIVED TO ROLE SANCTIONS_ANALYST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.DERIVED TO ROLE SANCTIONS_ANALYST';

    -- SANCTIONS_DATA_SCIENTIST: Read analytics + ML schema read/write
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_DATA_SCIENTIST';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DATA_SCIENTIST';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.ML TO ROLE SANCTIONS_DATA_SCIENTIST';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.GENAI TO ROLE SANCTIONS_DATA_SCIENTIST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DATA_SCIENTIST';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DATA_SCIENTIST';

    -- SANCTIONS_COMPLIANCE_OFFICER: Read access to everything
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_COMPLIANCE_OFFICER';
    EXECUTE IMMEDIATE 'GRANT USAGE ON ALL SCHEMAS IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_COMPLIANCE_OFFICER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_COMPLIANCE_OFFICER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL VIEWS IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_COMPLIANCE_OFFICER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_COMPLIANCE_OFFICER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE VIEWS IN DATABASE ' || db_name || ' TO ROLE SANCTIONS_COMPLIANCE_OFFICER';

    -- SANCTIONS_DBT_RUNNER: Transform role - read raw, write curated/analytics/derived
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.RAW TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.RAW TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.RAW TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.STAGING TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.CURATED TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_DBT_RUNNER';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.DERIVED TO ROLE SANCTIONS_DBT_RUNNER';

    -- SANCTIONS_STREAMLIT_APP: Read analytics + consumption
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_STREAMLIT_APP';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_STREAMLIT_APP';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.CONSUMPTION TO ROLE SANCTIONS_STREAMLIT_APP';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_STREAMLIT_APP';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL VIEWS IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_STREAMLIT_APP';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_STREAMLIT_APP';

    -- SANCTIONS_ML_PIPELINE: Read analytics, read/write ML + GENAI
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db_name || ' TO ROLE SANCTIONS_ML_PIPELINE';
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ML_PIPELINE';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.ML TO ROLE SANCTIONS_ML_PIPELINE';
    EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES ON SCHEMA ' || db_name || '.GENAI TO ROLE SANCTIONS_ML_PIPELINE';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ML_PIPELINE';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN SCHEMA ' || db_name || '.ANALYTICS TO ROLE SANCTIONS_ML_PIPELINE';

    RETURN 'Grants applied successfully for ' || db_name;
END;
$$;

