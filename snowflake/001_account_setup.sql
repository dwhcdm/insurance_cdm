CREATE OR REPLACE PROCEDURE SANCTIONS_DEV.PUBLIC.CREATE_SCHEMA_STRUCTURE(db_name VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
    -- Bronze / Raw layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.RAW
        DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = ''Raw data landing zone - Bronze layer''';

    -- Staging layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.STAGING
        DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = ''Staging area for data transformations''';

    -- Silver / Curated layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.CURATED
        DATA_RETENTION_TIME_IN_DAYS = 7
        COMMENT = ''Curated data - Silver layer''';

    -- Gold / Analytics layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.ANALYTICS
        DATA_RETENTION_TIME_IN_DAYS = 90
        COMMENT = ''Analytics-ready data - Gold layer''';

    -- Derived / Aggregates
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.DERIVED
        DATA_RETENTION_TIME_IN_DAYS = 90
        COMMENT = ''Pre-aggregated derived tables''';

    -- ML / Feature store
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.ML
        DATA_RETENTION_TIME_IN_DAYS = 30
        COMMENT = ''Machine learning feature store and model artifacts''';

    -- GenAI layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.GENAI
        DATA_RETENTION_TIME_IN_DAYS = 30
        COMMENT = ''Generative AI prompts, embeddings, and outputs''';

    -- Governance layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.GOVERNANCE
        DATA_RETENTION_TIME_IN_DAYS = 365
        COMMENT = ''Data governance, lineage, and audit logs''';

    -- Consumption layer
    EXECUTE IMMEDIATE 'CREATE SCHEMA IF NOT EXISTS ' || db_name || '.CONSUMPTION
        DATA_RETENTION_TIME_IN_DAYS = 30
        COMMENT = ''Consumption layer for Streamlit and external tools''';

    RETURN 'Schema structure created successfully for ' || db_name;
END;
$$;

-- Apply schema structure to all environments
CALL SANCTIONS_DEV.PUBLIC.CREATE_SCHEMA_STRUCTURE('SANCTIONS_DEV');
CALL SANCTIONS_DEV.PUBLIC.CREATE_SCHEMA_STRUCTURE('SANCTIONS_TEST');
